"""Generated views: markdown rendered on demand from the tables. They are read-only output, never a source of truth and
never edited by hand; ask again and they are current. (changelog and bugs live in main.py and service.py.)"""
from fastapi import HTTPException

from . import refs, sessions

NOTE = "_Generated by Viber from its tables. Do not edit by hand._"
CLOSED = ("Closed", "Done", "Fixed", "Won't Fix")


def _table(headers: list[str], rows: list[list]) -> list[str]:
    if not rows:
        return ["_None._"]
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c if c is not None else "").replace("|", "/").replace("\n", " ") for c in r) + " |" for r in rows]
    return out


def status(connection, project: dict) -> str:
    pid = project["id"]
    bugs = connection.execute("SELECT key, severity, title, status FROM item WHERE project_id = %s AND kind = 'bug' AND status <> ALL(%s) "
                              "ORDER BY CASE severity WHEN 'Critical' THEN 0 WHEN 'High' THEN 1 WHEN 'Medium' THEN 2 ELSE 3 END, created_at DESC LIMIT 15", (pid, list(CLOSED))).fetchall()
    n = lambda sql, *a: connection.execute(sql, (pid, *a)).fetchone()["n"]
    lines = [f"# STATUS - {project['name']}", "", NOTE, "",
             f"Open bugs: {n('SELECT count(*) AS n FROM item WHERE project_id=%s AND kind=%s AND status <> ALL(%s)', 'bug', list(CLOSED))}"
             f" | Open work: {n('SELECT count(*) AS n FROM item WHERE project_id=%s AND kind<>%s AND status <> ALL(%s)', 'bug', list(CLOSED))}"
             f" | Decisions awaiting you: {n('SELECT count(*) AS n FROM decision WHERE project_id=%s AND status=%s', 'Proposed')}"
             f" | Rules awaiting you: {n('SELECT count(*) AS n FROM rule WHERE project_id=%s AND status=%s', 'proposed')}", ""]
    lines += ["## Active sessions"] + [f"- {s['tag']} ({s['state']}) {s['goal'] or 'no goal'}" for s in sessions.active_sessions(connection, project)] or ["_None._"]
    lines += ["", "## Plans"]
    for p in refs.list_plans(connection, project):
        if p["status"] in ("Active", "Draft"):
            view = refs.plan_view(connection, project, p["key"])
            lines.append(f"- {p['key']} [{p['status']}] {p['title']}: {view['counts']['settled']} of {view['counts']['total']} settled")
    lines += ["", "## Open bugs (worst first)"] + _table(["Key", "Severity", "Title", "Status"], [[b["key"], b["severity"], b["title"], b["status"]] for b in bugs])
    flagged = connection.execute("SELECT key, title, gate_reason FROM item WHERE project_id = %s AND gate = 'flagged' AND status <> ALL(%s)", (pid, list(CLOSED))).fetchall()
    lines += ["", "## Flagged for you"] + _table(["Key", "Title", "Why"], [[f["key"], f["title"], f["gate_reason"]] for f in flagged])
    recent = connection.execute("SELECT occurred_on, summary FROM change WHERE project_id = %s ORDER BY occurred_on DESC, id DESC LIMIT 8", (pid,)).fetchall()
    lines += ["", "## Recent changes"] + [f"- {c['occurred_on']} {c['summary']}" for c in recent] or ["_None._"]
    return "\n".join(lines) + "\n"


def adr(connection, project: dict) -> str:
    rows = connection.execute("SELECT key, status, title, decided_on, superseded_by FROM decision WHERE project_id = %s AND status <> 'Reserved' "
                              "ORDER BY decided_on DESC NULLS LAST, key DESC", (project["id"],)).fetchall()
    lines = [f"# DECISIONS - {project['name']}", "", NOTE, ""]
    return "\n".join(lines + _table(["Key", "Status", "Title", "Decided", "Superseded by"],
                                    [[r["key"], r["status"], r["title"], r["decided_on"], r["superseded_by"]] for r in rows])) + "\n"


def rules(connection, project: dict) -> str:
    rows = connection.execute("SELECT scope, category, text FROM rule WHERE project_id = %s AND status = 'accepted' ORDER BY scope, category, created_at", (project["id"],)).fetchall()
    waiting = connection.execute("SELECT count(*) AS n FROM rule WHERE project_id = %s AND status = 'proposed'", (project["id"],)).fetchone()["n"]
    lines = [f"# RULES - {project['name']}", "", NOTE, "", f"{len(rows)} accepted. {waiting} proposed, waiting for a human.", ""]
    scope = None
    for r in rows:
        if r["scope"] != scope:
            scope = r["scope"]
            lines += ["", f"## {scope}"]
        lines.append(f"- ({r['category']}) {r['text']}")
    return "\n".join(lines) + "\n"


def specs(connection, project: dict) -> str:
    rows = connection.execute("SELECT key, kind, component_key, statement, status FROM spec WHERE project_id = %s AND status <> 'Dropped' "
                              "ORDER BY coalesce(component_key, ''), kind, key", (project["id"],)).fetchall()
    lines = [f"# SPECS - {project['name']}", "", NOTE, ""]
    component = object()
    for r in rows:
        if r["component_key"] != component:
            component = r["component_key"]
            lines += ["", f"## {component or '(no component)'}"]
        lines.append(f"- {r['key']} [{r['kind']}, {r['status']}] {r['statement']}")
    return "\n".join(lines) + "\n"


def plans(connection, project: dict) -> str:
    lines = [f"# PLANS - {project['name']}", "", NOTE]
    for p in refs.list_plans(connection, project):
        lines += ["", refs.plan_text(refs.plan_view(connection, project, p["key"]))]
    return "\n".join(lines) + "\n"


def backlog(connection, project: dict) -> str:
    rows = connection.execute("SELECT key, kind, lane, status, title FROM item WHERE project_id = %s AND kind <> 'bug' AND status <> ALL(%s) "
                              "ORDER BY lane, created_at", (project["id"], list(CLOSED))).fetchall()
    lines = [f"# BACKLOG - {project['name']}", "", NOTE, ""]
    return "\n".join(lines + _table(["Key", "Kind", "Lane", "Status", "Title"], [[r["key"], r["kind"], r["lane"], r["status"], r["title"]] for r in rows])) + "\n"


RENDERERS = {"status": status, "adr": adr, "rules": rules, "specs": specs, "plans": plans, "backlog": backlog}


def render(connection, project: dict, name: str) -> str:
    if name not in RENDERERS:
        raise HTTPException(404, f"view is one of {', '.join(RENDERERS)}, changelog, bugs")
    return RENDERERS[name](connection, project)
