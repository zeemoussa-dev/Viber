def call(client, project_key, name, **arguments):
    body = {"jsonrpc": "2.0", "id": 1, "method": "tools/call",
            "params": {"name": name, "arguments": {"project": project_key, **arguments}}}
    return client.post("/mcp", json=body).json()["result"]["content"][0]["text"]


def seed(client, key):
    base = f"/v1/projects/{key}"
    client.post(f"{base}/decisions", json={"key": "ADR-v3.001", "title": "Rows not files", "decision": "Everything is a row.", "decided_on": "2026-11-26"})
    call(client, key, "viber_spec_add", text="Backups are verified.\nRecall has checks.", component="viber")
    client.post(f"{base}/items", json={"kind": "bug", "title": "Heartbeat refused", "severity": "High"})
    client.post(f"{base}/items", json={"kind": "bug", "title": "Old bug", "severity": "Low", "status": "Fixed"})
    client.post(f"{base}/items", json={"kind": "task", "title": "Write the backup job", "lane": "standard"})
    rule = client.post(f"{base}/memory/rules", json={"text": "Never store secrets in memory.", "category": "constraint"}).json()
    client.post(f"{base}/memory/rules/{rule['id']}/accept")
    call(client, key, "viber_plan", key="PLAN-a", title="Make it solid", goal="Reliable memory")
    call(client, key, "viber_plan_add", plan="PLAN-a", members=["spec:REQ-001", "decision:ADR-v3.001"])


def test_views_are_markdown_made_from_the_tables(client, project_key):
    seed(client, project_key)
    base = f"/v1/projects/{project_key}/views"
    status = client.get(f"{base}/status").text
    assert "# STATUS" in status and "Open bugs: 1" in status and "Heartbeat refused" in status and "Old bug" not in status
    assert "PLAN-a" in status and "Generated by Viber" in status
    assert "| ADR-v3.001 | Accepted | Rows not files |" in client.get(f"{base}/adr").text
    assert "Never store secrets in memory." in client.get(f"{base}/rules").text
    specs = client.get(f"{base}/specs").text
    assert "## viber" in specs and "REQ-001 [requirement, Draft] Backups are verified." in specs
    assert "PLAN-a [Draft] Make it solid" in client.get(f"{base}/plans").text
    assert "Write the backup job" in client.get(f"{base}/backlog").text


def test_the_older_views_still_answer(client, project_key):
    seed(client, project_key)
    base = f"/v1/projects/{project_key}/views"
    assert client.get(f"{base}/changelog").status_code == 200
    assert "BUGS" in client.get(f"{base}/bugs").text
